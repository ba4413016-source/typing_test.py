@lru_cache(maxsize=2)
def _corpus_words(language: str) -> tuple[str, ...]:
    """Return clean, distinct words sourced from wordfreq's language corpus."""
    pattern = (
        r"\p{Latin}[\p{Latin}\p{M}]*"
        if language == "en"
        else r"\p{Arabic}[\p{Arabic}\p{M}]*"
    )
    accepted: list[str] = []
    seen: set[str] = set()
    for raw in top_n_list(language, 50_000):
        word = unicodedata.normalize("NFC", raw.strip())
        folded = word.casefold()
        if (
            folded in seen
            or folded in _BLOCKED[language]
            or folded in _COMMON[language]
        ):
            continue
        if (
            not regex.fullmatch(pattern, word, flags=regex.VERSION1)
            or not word
            or not word[0].isalpha()
            or any(
                not char.isalpha() and not unicodedata.category(char).startswith("M")
                for char in word
            )
        ):
            continue
        length = len(regex.findall(r"\X", word))
        if not 2 <= length <= 14:
            continue
        seen.add(folded)
        accepted.append(word)
    return tuple(accepted)


def warm_word_corpora() -> None:
    """Populate the per-process word cache before a user requests a round."""
    _corpus_words("ar")
    _corpus_words("en")


def _pick_words(
    language: str, count: int, rng: Any, length_range: tuple[int, int] | None = None
) -> list[str]:
    words = _corpus_words(language)
    if length_range is not None:
        minimum, maximum = length_range
        words = tuple(word for word in words if minimum <= len(word) <= maximum)
    if count > len(words):
        raise ValueError(
            "The language corpus does not contain enough distinct usable words"
        )
    return rng.sample(words, count)


def _make_text(game: str, language: str, difficulty: str, rng: Any) -> str:
    scenes, actions, endings = _TEXT_PARTS[language][game]
    desired = _LEVEL_LENGTHS[difficulty]
    parts: list[str] = []
    length = 0
    # Every generated unit is a complete, punctuation-terminated sentence.
    # The modest overshoot keeps grammar intact while staying far below 600 chars.
    for _ in range(8):
        word = rng.choice(_pick_words(language, 1, rng))
        sentence = (
            f"{rng.choice(scenes)}, {rng.choice(actions).format(word=word)}. "
            f"{rng.choice(endings)}"
        )
        sentence = sentence.rstrip(".؟?! ") + "."
        if length and length + 1 + len(sentence) > 600:
            break
        parts.append(sentence)
        length += len(sentence) + (1 if len(parts) > 1 else 0)
        if length >= desired:
            break
    text = " ".join(parts)
    if len(text) > 600:
        raise RuntimeError("Generated text exceeded the safety limit")
    return text


def generate_target(
    game: str, difficulty: str, language: str, count: int | None = None, rng: Any = None
) -> GeneratedTarget:
    """Generate one target on demand.

    For repeat rounds, ``count`` is mandatory (1–20); no implicit default is
    chosen so callers control round size explicitly. For text games it must be
    omitted. ``rng`` may be a ``random.Random``-compatible object for seeded use.
    """
    if game not in _GAMES:
        raise ValueError("game must be one of sentences, stories, news, repeat")
    if difficulty not in _LEVEL_LENGTHS:
        raise ValueError("difficulty must be easy, medium, or hard")
    if language not in _LANGUAGES:
        raise ValueError("language must be ar or en")
    chooser = rng if rng is not None else random.SystemRandom()
    if not callable(getattr(chooser, "choice", None)) or not callable(
        getattr(chooser, "sample", None)
    ):
        raise ValueError("rng must provide choice() and sample()")

    if game == "repeat":
        if (
            count is None
            or isinstance(count, bool)
            or not isinstance(count, int)
            or not _REPEAT_MIN <= count <= _REPEAT_MAX
        ):
            raise ValueError(
                "repeat count is required and must be an integer from 1 to 20"
            )
        words = _pick_words(language, count, chooser, _REPEAT_LENGTHS[difficulty])
        target = " ".join(word for word in words for _ in range(3))
        display = " · ".join(f"({word})3" for word in words)
        return GeneratedTarget(
            target,
            display,
            game,
            difficulty,
            language,
            count,
            {"synthetic": True, "repetitions_per_word": 3},
        )

    if count is not None:
        raise ValueError("count is only valid for repeat rounds")
    target = _make_text(game, language, difficulty, chooser)
    return GeneratedTarget(
        target,
        target,
        game,
        difficulty,
        language,
        None,
        {"synthetic": True, "factual_news": False if game == "news" else None},
    )


def _is_letter_or_number(cluster: str) -> bool:
    return bool(regex.search(r"[\p{L}\p{N}]", cluster, flags=regex.VERSION1))


def _edit_cost(cluster: str) -> int:
    return 2 if _is_letter_or_number(cluster) else 1


def _error_kind(expected: str, actual: str) -> str:
    if _is_letter_or_number(expected) or _is_letter_or_number(actual):
        return "letter"
    if (expected and expected.isspace()) or (actual and actual.isspace()):
        return "spacing"
    return "punctuation"


def score_attempt(expected: str, typed: str, elapsed_seconds: float) -> dict[str, Any]:
    """Score a partial/overlong attempt with weighted grapheme edit alignment.

    Letter/number edits cost 2, whitespace or punctuation-only edits cost 1.
    Text is NFC-normalized before segmenting into Unicode grapheme clusters.
    """
    if not isinstance(expected, str) or not isinstance(typed, str):
        raise ValueError("expected and typed must be strings")
    if len(expected) > 600 or len(typed) > 1200:
        raise ValueError(
            "expected is limited to 600 code points and typed to 1200 code points"
        )
    try:
        elapsed = float(elapsed_seconds)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError("elapsed_seconds must be a finite positive number") from exc
    if not math.isfinite(elapsed) or elapsed <= 0:
        raise ValueError("elapsed_seconds must be a finite positive number")

    expected = unicodedata.normalize("NFC", expected)
    typed = unicodedata.normalize("NFC", typed)
    left = regex.findall(r"\X", expected)
    right = regex.findall(r"\X", typed)
    n, m = len(left), len(right)
    if n > 600 or m > 1200:
        raise ValueError(
            "expected is limited to 600 graphemes and typed to 1200 graphemes"
        )

    # Classify each grapheme once; the dynamic-programming inner loop then uses
    # only list lookups and integer arithmetic (no per-cell regex calls).
    left_flags = [_is_letter_or_number(cluster) for cluster in left]
    right_flags = [_is_letter_or_number(cluster) for cluster in right]
    left_costs = [2 if flag else 1 for flag in left_flags]
    right_costs = [2 if flag else 1 for flag in right_flags]

    # Two cost rows plus a compact byte-per-cell traceback (at most ~721 KB).
    trace = bytearray((n + 1) * (m + 1))
    width = m + 1
    previous = [0] * width
    for j in range(1, width):
        previous[j] = previous[j - 1] + right_costs[j - 1]
        trace[j] = 3  # insertion
    current = [0] * width
    for i in range(1, n + 1):
        left_cost = left_costs[i - 1]
        left_is_letter = left_flags[i - 1]
        current[0] = previous[0] + left_cost
        trace[i * width] = 2  # deletion
        for j in range(1, m + 1):
            same = left[i - 1] == right[j - 1]
            right_is_letter = right_flags[j - 1]
            diagonal = previous[j - 1] + (
                0 if same else (2 if left_is_letter or right_is_letter else 1)
            )
            deletion = previous[j] + left_cost
            insertion = current[j - 1] + right_costs[j - 1]
            best = min(diagonal, deletion, insertion)
            current[j] = best
            if diagonal == best:
                trace[i * width + j] = 0 if same else 1  # match/substitution
            elif deletion == best:
                trace[i * width + j] = 2
            else:
                trace[i * width + j] = 3
        previous, current = current, previous

    edits: list[dict[str, Any]] = []
    correct_characters = 0
    penalty = 0
    letter_errors = spacing_errors = punctuation_errors = 0
    i, j = n, m
    while i or j:
        action = trace[i * width + j]
        if action == 0:  # exact match
            correct_characters += 1
            i -= 1
            j -= 1
            continue
        if action == 1:
            exp, act = left[i - 1], right[j - 1]
            operation = "substitute"
            position = i
            is_letter_error = left_flags[i - 1] or right_flags[j - 1]
            cost = 2 if is_letter_error else 1
            i -= 1
            j -= 1
        elif action == 2:
            exp, act = left[i - 1], ""
            operation = "delete"
            position = i
            is_letter_error = left_flags[i - 1]
            cost = left_costs[i - 1]
            i -= 1
        elif action == 3:
            exp, act = "", right[j - 1]
            operation = "insert"
            position = i + 1
            is_letter_error = right_flags[j - 1]
            cost = right_costs[j - 1]
            j -= 1
        else:  # Defensive guard for an invalid traceback state.
            raise RuntimeError("Invalid edit-alignment traceback")
        penalty += cost
        if is_letter_error:
            letter_errors += 1
        elif (exp and exp.isspace()) or (act and act.isspace()):
            spacing_errors += 1
        else:
            punctuation_errors += 1
        edits.append(
            {
                "operation": operation,
                "expected": exp,
                "actual": act,
                "position": position,
            }
        )

    edits.reverse()
    base_points = n
    max_length = max(n, m)
    accuracy = (100.0 * correct_characters / max_length) if max_length else 100.0
    minutes = elapsed / 60.0
    return {
        "points": max(0, base_points - penalty),
        "base_points": base_points,
        "penalty": penalty,
        "accuracy": accuracy,
        "wpm": correct_characters / 5.0 / minutes,
        "correct_characters": correct_characters,
        "error_count": len(edits),
        "letter_errors": letter_errors,
        "spacing_errors": spacing_errors,
        "punctuation_errors": punctuation_errors,
        "errors": edits[:12],
        "more_errors": max(0, len(edits) - 12),
    }
